#!/usr/bin/env node
/**
 * ADR-009 · PROTOCOL.md 单向同步
 * ---------------------------------------------------------------
 * `docs/04_接口协议与数据模型.md` 是唯一契约源；根目录 PROTOCOL.md 是它的
 * **发布副本**，供第三方客户端阅读（01 G9 / 02 §6 第 16 项）。
 *
 *   node scripts/sync-protocol.mjs           # 生成 PROTOCOL.md
 *   node scripts/sync-protocol.mjs --check   # CI 校验，不一致 exit 1（不写文件）
 *
 * 规则（06 §9）：改了 04 的字段，同 PR 必须同时提交 04 + PROTOCOL.md +
 * CHANGELOG.md，CI 用 --check 校验前两者一致，并校验 CHANGELOG 有 diff。
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'docs', '04_接口协议与数据模型.md')
const OUT = join(ROOT, 'PROTOCOL.md')

const banner = [
  '<!-- AUTO-GENERATED by scripts/sync-protocol.mjs — DO NOT EDIT MANUALLY -->',
  '<!-- 唯一契约源：docs/04_接口协议与数据模型.md ｜ ADR-009 ｜ 单向同步 -->',
  '',
  '> 本文件是 `04` 的发布副本，供第三方客户端阅读（01 G9 / 02 §6 第 16 项）。',
  '> 字段变更请在 `docs/04_接口协议与数据模型.md` 中修改，然后运行',
  '> `node scripts/sync-protocol.mjs` 重新生成；CI 用 `--check` 校验一致性。',
  '> 分隔线以下内容与 `04` 逐字相同。',
  '',
  '---',
  '',
].join('\n')

const generated = banner + readFileSync(SRC, 'utf8')

if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) {
    console.error(`FAIL: ${OUT} 不存在，请运行 node scripts/sync-protocol.mjs`)
    process.exit(1)
  }
  if (readFileSync(OUT, 'utf8') !== generated) {
    console.error('FAIL: PROTOCOL.md 与 docs/04 不同步；重新生成后再提交')
    process.exit(1)
  }
  console.log('OK: PROTOCOL.md 与 docs/04 一致')
  process.exit(0)
}

writeFileSync(OUT, generated, 'utf8')
console.log(`generated ${OUT} (${generated.length} chars)`)
